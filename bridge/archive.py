"""The map of the context archive.

Raw transcripts are copied to ``bridge-logs/<date>/raw/<session-id>.jsonl``
and pre-compaction copies to ``snapshots/``. After a few nights that is a
folder of filenames that are session ids, and a session id answers nothing:
which half of the pair wrote it, what it was asked to do, how big it got,
where it compacted. This walks those folders and writes down what each file
is - a per-date ``index.json``, a global ``map.json``, and ``MAP.md`` for a
human to read.

Two rules it does not bend.

**Nothing is guessed.** A file is attributed to a role and a project only
from a session id the bridge has a record of. A file whose id is not on
record is marked unknown - never attributed by being the newest file in the
folder, by sitting next to one that is known, or by the folder it is in
(§1.5). The transcript's own ``cwd`` is recorded separately, as the fact it
is, and is not promoted to "project".

**The size is the named fields.** Carried context is
``input_tokens + cache_creation_input_tokens + cache_read_input_tokens``
(§1.3), by name. Never a sum over every key containing "token": the usage
block nests a ``cache_creation`` breakdown and repeats the whole thing under
``iterations``, so a wildcard counts the same tokens three times.

MAP.md carries no clock: the same archive renders the same file, so a
rebuild that changes nothing changes nothing on disk.
"""

import json
import os
import re
import subprocess
import threading
import time

from . import store

# §1.3: what the conversation occupies is the input context of the last
# request. Output tokens belong to the *next* request, not this one. The
# definition is store's, so the map and the bridge's own meters can never
# answer differently about the same file.
INPUT_TOKEN_FIELDS = store.CARRIED_CONTEXT_FIELDS

# Where the bridge keeps its own copies, under <project>/bridge-logs/<date>/.
KINDS = (("raw", "transcript"), ("snapshots", "snapshot"))

MAX_EXCERPT = 240

# A user row that is not a human typing: hooks, tool results, the bridge's
# own channel events, and the wrappers a slash command leaves behind.
NOT_A_HUMAN = (
    "<channel ", "<system-reminder>", "<command-message>", "<command-name>",
    "<local-command-stdout>", "<local-command-stderr>",
    "Caveat: The messages below were generated by the user while running "
    "local commands",
)

REPORT_PATTERNS = (re.compile(r"Executor report (\d+)\s*:"),
                   re.compile(r'kind="report"\s+report="(\d+)"'))


def _rows(path, limit_bytes=0):
    """Every json row of a transcript, bad lines skipped rather than fatal."""
    out = []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    out.append(json.loads(line))
                except Exception:
                    continue
    except Exception:
        return []
    return out


def carried_tokens(usage):
    """Carried context from a usage block, by field name (§1.3).

    Returns (tokens, fields_present) so the map can show which terms the
    number was actually built from instead of asserting a total nobody can
    check. The arithmetic is store's, shared with every other reader of it.
    """
    return store.carried_from_usage(usage)


def _text_of(msg):
    """The readable text of a message, whatever shape its content is in."""
    content = (msg or {}).get("content")
    if isinstance(content, str):
        return content
    parts = []
    for block in (content or []):
        if isinstance(block, dict) and block.get("type") == "text":
            parts.append(block.get("text") or "")
    return "\n".join(p for p in parts if p)


def _user_text(row, allow_meta=False):
    """The text of a user row, or "" if it is not one carrying any.

    isMeta marks content the client injected rather than the person typing,
    which is exactly what disqualifies a row from being the human excerpt -
    and exactly what a bridge task is, so that caller asks for it.
    """
    if row.get("type") != "user" or row.get("isSidechain"):
        return ""
    if row.get("isMeta") and not allow_meta:
        return ""
    content = (row.get("message") or {}).get("content")
    if isinstance(content, list):
        # a list of blocks is a tool result unless it carries real text
        if not any(isinstance(b, dict) and b.get("type") == "text"
                   for b in content):
            return ""
    return _text_of(row.get("message") or {}).strip()


def _is_human(row):
    """Did a person type this?

    Tool results, hook output and the bridge's own channel events all arrive
    as user rows. Only what a human actually wrote tells you what a session
    was for, which is the whole point of the excerpt.
    """
    text = _user_text(row)
    return bool(text) and not text.startswith(NOT_A_HUMAN)


def _bridge_task(row):
    """The first task the bridge handed this session, as its own text.

    An executor is never spoken to by a human: its instructions arrive as
    channel tasks, so the human-instruction excerpt is empty for exactly
    half the archive - which is the half doing the work. The task text is
    what that session was about, and it is quoted rather than guessed at,
    with the excerpt's source recorded next to it.
    """
    text = _user_text(row, allow_meta=True)
    if not text.startswith("<channel "):
        return ""
    if 'kind="task"' not in text[:120]:
        return ""
    body = re.sub(r"^<channel[^>]*>", "", text).strip()
    body = re.sub(r"</channel>\s*$", "", body).strip()
    return body


def _excerpt(text):
    out = " ".join((text or "").split())
    return out[:MAX_EXCERPT] + ("..." if len(out) > MAX_EXCERPT else "")


def scan_file(path, known=None):
    """Everything the map records about one archived transcript."""
    known = known or {}
    name = os.path.basename(path)
    sid = os.path.splitext(name)[0]
    # snapshots are "<session-id>-<HHMMSS>.jsonl"
    stamp = ""
    m = re.match(r"^(.*)-(\d{6})$", sid)
    if m:
        sid, stamp = m.group(1), m.group(2)

    rec = {
        "file": name,
        "session_id": sid,
        "taken_at": stamp,
        "role": "unknown",
        "project": "unknown",
        "attribution": "no record of this session id",
        "turns": 0,
        "user_messages": 0,
        "first_at": "", "last_at": "",
        "carried_tokens": None, "token_fields": [],
        "model": "",
        "compactions": [],
        "iterations": [],
        "excerpt": "", "excerpt_source": "",
        "cwd_recorded": "",
        "bytes": 0,
    }
    try:
        rec["bytes"] = os.path.getsize(path)
    except Exception:
        pass

    # Role and project come from the bridge's own records and nowhere else.
    entry = known.get(sid)
    if entry:
        rec["role"] = entry.get("role") or "unknown"
        rec["project"] = entry.get("project") or "unknown"
        rec["attribution"] = entry.get("how") or "bridge session record"

    rows = _rows(path)
    if not rows:
        rec["attribution"] += "; file unreadable or empty"
        return rec

    iterations, last_usage = set(), None
    for row in rows:
        at = row.get("timestamp") or ""
        if at:
            if not rec["first_at"] or at < rec["first_at"]:
                rec["first_at"] = at
            if at > rec["last_at"]:
                rec["last_at"] = at
        if not rec["cwd_recorded"] and row.get("cwd"):
            rec["cwd_recorded"] = row["cwd"]

        kind = row.get("type")
        if kind == "assistant":
            rec["turns"] += 1
            msg = row.get("message") or {}
            if msg.get("usage"):
                last_usage = msg["usage"]
            if msg.get("model"):
                rec["model"] = msg["model"]
        elif kind == "user":
            rec["user_messages"] += 1
            if rec["excerpt_source"] != "human":
                if _is_human(row):
                    rec["excerpt"] = _excerpt(_text_of(row.get("message")
                                                       or {}))
                    rec["excerpt_source"] = "human"
                elif not rec["excerpt"]:
                    task = _bridge_task(row)
                    if task:
                        rec["excerpt"] = _excerpt(task)
                        rec["excerpt_source"] = "bridge task"

        if kind == "system" and row.get("subtype") == "compact_boundary":
            meta = row.get("compactMetadata") or {}
            rec["compactions"].append({
                "at": at,
                "trigger": meta.get("trigger") or "",
                "pre_tokens": meta.get("preTokens"),
                "post_tokens": meta.get("postTokens"),
            })

        # Iteration numbers, from the report the executor sent and from the
        # channel envelope the planner received it in.
        blob = _text_of(row.get("message") or {})
        if blob:
            for pat in REPORT_PATTERNS:
                for hit in pat.findall(blob):
                    try:
                        iterations.add(int(hit))
                    except Exception:
                        pass

    rec["iterations"] = sorted(iterations)
    tokens, fields = carried_tokens(last_usage)
    rec["carried_tokens"] = tokens
    rec["token_fields"] = fields
    return rec


def logs_root(project_dir):
    return os.path.join(project_dir, "bridge-logs")


def dates(project_dir):
    root = logs_root(project_dir)
    if not os.path.isdir(root):
        return []
    out = []
    for name in os.listdir(root):
        if re.match(r"^\d{4}-\d{2}-\d{2}$", name) and \
                os.path.isdir(os.path.join(root, name)):
            out.append(name)
    return sorted(out)


def build_date(project_dir, date, known=None):
    """Index one day's archived files, and leave index.json beside them."""
    day = os.path.join(logs_root(project_dir), date)
    files = []
    for folder, kind in KINDS:
        d = os.path.join(day, folder)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if not name.endswith(".jsonl"):
                continue
            rec = scan_file(os.path.join(d, name), known)
            rec["kind"] = kind
            rec["path"] = "%s/%s/%s" % (date, folder, name)
            files.append(rec)
    files.sort(key=lambda r: (r.get("first_at") or "~", r["path"]))
    index = {"date": date, "files": files, "count": len(files)}
    if files:
        try:
            with open(os.path.join(day, "index.json"), "w",
                      encoding="utf-8") as fh:
                json.dump(index, fh, ensure_ascii=False, indent=1,
                          sort_keys=True)
        except Exception:
            pass
    return index


def build(project_dir, known=None):
    """Rebuild the whole map for one project. Returns it; also writes it."""
    known = known or {}
    days = [build_date(project_dir, d, known) for d in dates(project_dir)]
    days = [d for d in days if d["count"]]
    files = [f for d in days for f in d["files"]]

    sessions = {}
    for f in files:
        s = sessions.setdefault(f["session_id"], {
            "session_id": f["session_id"], "role": f["role"],
            "project": f["project"], "files": 0, "turns": 0,
            "first_at": "", "last_at": "", "iterations": set(),
            "compactions": 0, "carried_tokens": None, "excerpt": "",
            "excerpt_source": ""})
        s["files"] += 1
        s["turns"] += f["turns"]
        s["compactions"] += len(f["compactions"])
        s["iterations"].update(f["iterations"])
        if f["first_at"] and (not s["first_at"] or f["first_at"] < s["first_at"]):
            s["first_at"] = f["first_at"]
        if f["last_at"] > s["last_at"]:
            s["last_at"] = f["last_at"]
            # the newest file of a session is the one whose size still stands
            s["carried_tokens"] = f["carried_tokens"]
        # a human's own words outrank a task the bridge relayed, whichever
        # file each turned up in
        if f["excerpt"] and (s["excerpt_source"] != "human"
                             and (not s["excerpt"]
                                  or f["excerpt_source"] == "human")):
            s["excerpt"] = f["excerpt"]
            s["excerpt_source"] = f["excerpt_source"]
    for s in sessions.values():
        s["iterations"] = sorted(s["iterations"])

    m = {
        "project": project_dir,
        "generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "dates": [d["date"] for d in days],
        "files": files,
        "sessions": [sessions[k] for k in sorted(sessions)],
        "totals": {
            "files": len(files),
            "sessions": len(sessions),
            "turns": sum(f["turns"] for f in files),
            "compactions": sum(len(f["compactions"]) for f in files),
            "bytes": sum(f["bytes"] for f in files),
            "unknown_files": len([f for f in files
                                  if f["role"] == "unknown"]),
        },
    }
    root = logs_root(project_dir)
    if os.path.isdir(root):
        try:
            with open(os.path.join(root, "map.json"), "w",
                      encoding="utf-8") as fh:
                json.dump(m, fh, ensure_ascii=False, indent=1, sort_keys=True)
        except Exception:
            pass
        try:
            with open(os.path.join(root, "MAP.md"), "w",
                      encoding="utf-8") as fh:
                fh.write(render_md(m))
        except Exception:
            pass
    return m


def _k(n):
    if n is None:
        return "-"
    return "%dk" % (n // 1000) if n >= 1000 else str(n)


def _when(ts):
    return (ts or "")[:19].replace("T", " ")


def render_md(m):
    """MAP.md: the same archive renders the same bytes, so no clock in it."""
    t = m.get("totals") or {}
    out = ["# Archive map", "",
           "%d files · %d sessions · %d turns · %d compactions · %.1f MB"
           % (t.get("files", 0), t.get("sessions", 0), t.get("turns", 0),
              t.get("compactions", 0), (t.get("bytes", 0) or 0) / 1048576.0),
           ""]
    if t.get("unknown_files"):
        out += ["%d file%s could not be attributed: the bridge has no record "
                "of the session id. They are listed as unknown rather than "
                "guessed at." % (t["unknown_files"],
                                 "" if t["unknown_files"] == 1 else "s"), ""]
    if not m.get("files"):
        out += ["Nothing archived yet.", ""]
        return "\n".join(out)

    out += ["## Sessions", "",
            "| session | role | project | turns | carried | compactions | "
            "iterations | what it was about | from |",
            "|---|---|---|---|---|---|---|---|---|"]
    for s in m.get("sessions") or []:
        out.append("| `%s` | %s | %s | %d | %s | %d | %s | %s | %s |"
                   % (s["session_id"][:8], s["role"], s["project"],
                      s["turns"], _k(s.get("carried_tokens")),
                      s["compactions"], _rng(s.get("iterations")),
                      (s.get("excerpt") or "").replace("|", "/")[:110],
                      s.get("excerpt_source") or "-"))
    out += ["", "## Files", ""]
    for date in m.get("dates") or []:
        out += ["### %s" % date, "",
                "| file | kind | session | role | turns | carried | first | "
                "last | compactions |", "|---|---|---|---|---|---|---|---|---|"]
        for f in m["files"]:
            if not f["path"].startswith(date + "/"):
                continue
            comp = "; ".join("%s %s→%s" % (c.get("trigger") or "?",
                                           _k(c.get("pre_tokens")),
                                           _k(c.get("post_tokens")))
                             for c in f["compactions"]) or "-"
            out.append("| `%s` | %s | `%s` | %s | %d | %s | %s | %s | %s |"
                       % (f["file"], f["kind"], f["session_id"][:8], f["role"],
                          f["turns"], _k(f.get("carried_tokens")),
                          _when(f["first_at"]), _when(f["last_at"]), comp))
        out.append("")
    return "\n".join(out)


def _rng(nums):
    """[1,2,3,7] -> "1-3, 7" - iteration numbers as a human writes them."""
    if not nums:
        return "-"
    spans, start, prev = [], nums[0], nums[0]
    for n in nums[1:]:
        if n == prev + 1:
            prev = n
            continue
        spans.append((start, prev))
        start = prev = n
    spans.append((start, prev))
    return ", ".join(str(a) if a == b else "%d-%d" % (a, b) for a, b in spans)


# ---- rebuilding without standing in anybody's way -------------------------
#
# The map is rebuilt after every raw copy the daemon makes, which is once per
# finished turn. Scanning is cheap but it is file work, and the Stop path is
# a hook the executor is blocked on - so it happens on a worker thread, one
# at a time per project, and a request that arrives mid-build sets a flag
# rather than starting a second one (§6: nothing slow on a request thread,
# nothing at all under the daemon's lock).

_lock = threading.Lock()
_running = set()      # project dirs currently being built
_again = set()        # project dirs asked for again mid-build
_last = {}            # project dir -> the map from the last build


def last_map(project_dir):
    """The map from the last build, or what is on disk, or nothing."""
    with _lock:
        m = _last.get(project_dir)
    if m:
        return m
    try:
        with open(os.path.join(logs_root(project_dir), "map.json"),
                  encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:
        return None


def build_now(project_dir, known=None):
    """Build, remember the result, and repeat if asked again mid-build."""
    while True:
        m = build(project_dir, known)
        with _lock:
            _last[project_dir] = m
            if project_dir in _again:
                _again.discard(project_dir)
                continue
            _running.discard(project_dir)
            return m


def rebuild_async(project_dir, known=None, done=None):
    """Kick a rebuild on a worker thread. Never raises, never blocks.

    Returns the thread when one was started, None when a build was already
    running - in which case it has been told to go round again, so the
    caller's change is still picked up.
    """
    if not project_dir or not os.path.isdir(logs_root(project_dir)):
        return None
    with _lock:
        if project_dir in _running:
            _again.add(project_dir)
            return None
        _running.add(project_dir)

    def run():
        try:
            m = build_now(project_dir, known)
            if done:
                done(m)
        except Exception:
            with _lock:
                _running.discard(project_dir)
                _again.discard(project_dir)

    t = threading.Thread(target=run, daemon=True)
    t.start()
    return t


# ---- searching the archive ------------------------------------------------
#
# A question about past work is answered by a separate Claude that reads the
# archive: it is given the map and told to open the files the map points at.
#
# It is a headless one-off - `claude -p`, no window, no channel, no role. It
# must never look like a member of the pair, so it gets none of the things
# that make one: no development-channels flag, no MCP config at all, and
# BRIDGE_NO_HOOKS in its environment, because it runs inside a watched
# project whose hooks and status line would otherwise report it as a session
# that had just started and then gone quiet.
#
# It reads and nothing else. The allow list names the three tools it needs;
# the deny list names the ones it must never have, because a deny outranks
# every permission mode - the same belt and braces the readonly planner uses.

READ_TOOLS = ("Read", "Grep", "Glob")
NO_TOOLS = ("Edit", "Write", "NotebookEdit", "Bash", "PowerShell",
            "WebFetch", "WebSearch", "Task", "Agent")

DEFAULT_MODEL = "sonnet"
DEFAULT_TIMEOUT = 600
# How many searches may run at once across all projects; config.json
# overrides it with "archive_parallel". Within one project it is always
# one, whatever this says.
DEFAULT_PARALLEL = 2

PROMPT = """You are answering one question about a pair of Claude Code \
sessions' own past work, from the archive they left on disk.

THE QUESTION
%(question)s

THE ARCHIVE
You are in the folder `bridge-logs`. It holds, per day:
  <date>/raw/<session-id>.jsonl        full transcripts, one line per event
  <date>/snapshots/<id>-<time>.jsonl   copies taken just before a compaction
  <date>/dialogue.md, dialogue/        readable per-iteration text
  <date>/handoff/                      what each session handed to its
                                       replacement
  INDEX.md                             one line per iteration
  MAP.md                               the index of the above (below in full)

MAP.md
%(map)s

WHAT TO DO
1. Work out from the map which files can hold the answer. The map gives you
   role, project, turn count, timestamps, iteration numbers and a line about
   what each session was doing - use it to choose, do not open everything.
2. Read them. The transcripts are JSON Lines: one object per line, with
   "type" of "user" or "assistant", a "timestamp", and the text under
   message.content (a string, or blocks with {"type": "text"}). Grep for
   terms first, then read around the hits - these files run to megabytes.
3. Answer the question.

THE ANSWER
Write it as markdown. Be concrete and quote the archive where quoting
settles it. Then, under a final `## Sources` heading, list every file you
actually read, one per line, as `<path>` followed by what you took from it
and the timestamp or iteration number if you have one. Cite only what you
opened. If the archive does not answer the question, say exactly that and
list where you looked - an honest miss is worth more than a plausible
answer assembled from nothing."""


def slug(text, n=40):
    out = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    return out[:n] or "question"


def extracts_dir(project_dir):
    d = os.path.join(logs_root(project_dir), "extracts")
    os.makedirs(d, exist_ok=True)
    return d


def build_command(question, model=None, claude="claude"):
    """The exact command line the search agent runs under.

    Kept apart from the running of it so a test can read it, and so the one
    place that decides what this process is allowed to do is readable in one
    screen.

    ``claude`` may be a list as well as a name, so the executable can be an
    interpreter plus a script - which is what the tests hand it, and what a
    machine where `claude` is not plainly on PATH can be configured with.
    """
    head = list(claude) if isinstance(claude, (list, tuple)) else [claude]
    return head + [
        "-p", question,
        "--model", model or DEFAULT_MODEL,
        "--allowedTools", ",".join(READ_TOOLS),
        "--disallowedTools", ",".join(NO_TOOLS),
        # no MCP servers at all: the project's .mcp.json would otherwise
        # hand this run the bridge channel and it would register as one
        "--strict-mcp-config",
        "--output-format", "text",
    ]


# run id -> record. Small, bounded, and in memory only: an extract that
# matters is on disk, and a run that was in flight when the bridge stopped
# did not finish.
RUNS = {}
_runlock = threading.Lock()
MAX_RUNS = 20


_runseq = [0]


def new_run_id():
    """A run id that is unique even when two projects start in the same
    millisecond.

    It used to be the millisecond clock alone, which was unique for as long
    as only one search could exist at a time. Once the seat became per
    project, two of them starting together got the same id, RUNS is keyed by
    id, and the second one silently replaced the first: the first project's
    seat vanished from the registry while its process was still running, so
    it could be asked the same question twice and the answer to one of them
    was thrown away.
    """
    with _runlock:
        _runseq[0] += 1
        return "s%d-%d" % (int(time.time() * 1000), _runseq[0])


def active_run(project_dir=None):
    """The run holding a seat: any of them, or this project's own.

    The argument is optional on purpose. Without it the answer is what it
    has always been - "is anything running at all" - which is what the
    panel and the suites ask, and what "nothing is left running" means at
    the end of a case. With it the question narrows to one project, which
    is what deciding whether to start a search now needs: a seat belongs to
    a project, not to the bridge.
    """
    want = store.norm(project_dir) if project_dir else None
    with _runlock:
        for rid, r in RUNS.items():
            if r.get("state") != "running":
                continue
            if want is None or store.norm(r.get("project")) == want:
                return rid, r
    return None, None


def running_runs():
    """Every run in flight right now, newest last. Used for the ceiling."""
    with _runlock:
        rows = [(rid, dict(r)) for rid, r in RUNS.items()
                if r.get("state") == "running"]
    rows.sort(key=lambda kv: kv[1].get("started") or 0)
    return rows


def _shortname(path):
    return os.path.basename((path or "").rstrip("\\/")) or "?"


def get_run(run_id):
    with _runlock:
        r = RUNS.get(run_id)
        return dict(r) if r else None


def recent_runs(limit=10):
    with _runlock:
        rows = sorted(RUNS.values(), key=lambda r: r.get("started") or 0,
                      reverse=True)
        return [dict(r) for r in rows[:limit]]


def _remember(rec):
    with _runlock:
        RUNS[rec["id"]] = rec
        if len(RUNS) > MAX_RUNS:
            for old in sorted(RUNS, key=lambda k: RUNS[k].get("started") or 0
                              )[:-MAX_RUNS]:
                if RUNS[old].get("state") != "running":
                    RUNS.pop(old, None)


def _cited(answer):
    """The files the agent says it read, from its own Sources section."""
    tail = re.split(r"^#+\s*Sources\s*$", answer or "", flags=re.M | re.I)
    if len(tail) < 2:
        return []
    out = []
    for line in tail[-1].splitlines():
        for hit in re.findall(r"`([^`]+)`", line) or \
                re.findall(r"([\w./\\-]+\.(?:jsonl|md))", line):
            if hit not in out:
                out.append(hit)
    return out[:40]


def write_extract(project_dir, rec):
    """The answer, on disk, with the question that produced it."""
    name = "%s-%s.md" % (time.strftime("%Y%m%d-%H%M%S",
                                       time.localtime(rec["started"])),
                         slug(rec["question"]))
    path = os.path.join(extracts_dir(project_dir), name)
    body = ["# %s" % rec["question"], "",
            "*asked %s · answered by %s in %ds*"
            % (time.strftime("%Y-%m-%d %H:%M:%S",
                             time.localtime(rec["started"])),
               rec.get("model") or DEFAULT_MODEL, int(rec.get("seconds") or 0)),
            "", rec.get("answer") or "", ""]
    if rec.get("cited"):
        body += ["---", "", "Files cited: %s"
                 % ", ".join("`%s`" % c for c in rec["cited"]), ""]
    try:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(body))
    except Exception:
        return None
    return path


def search(project_dir, question, model=None, timeout=None, claude="claude",
           journal=None, run_id=None):
    """Ask the archive a question. Blocking - callers use search_async.

    Returns the run record. A failure comes back as a record with
    state="failed" and a reason in it; nothing here raises, and nothing is
    ever left in state="running" (§1.6.11 - a failure has to arrive
    somewhere, with its reason).
    """
    def note(kind, text, level="log"):
        if journal:
            try:
                journal(kind, text, level)
            except Exception:
                pass

    rec = {"id": run_id or new_run_id(),
           "question": question, "project": project_dir,
           "model": model or DEFAULT_MODEL, "state": "running",
           "started": time.time(), "seconds": 0, "answer": "",
           "cited": [], "extract": "", "error": ""}
    _remember(rec)

    root = logs_root(project_dir)
    if not os.path.isdir(root):
        rec.update(state="failed",
                   error="there is no bridge-logs folder in %s, so there is "
                         "nothing to search" % project_dir)
        note("archive", "Archive search failed: %s" % rec["error"], "sound")
        return rec

    # The map is what the agent navigates by, so it is built first and
    # handed over inline rather than left to be found.
    try:
        build_now(project_dir, (rec.get("known") or None))
    except Exception:
        pass
    try:
        with open(os.path.join(root, "MAP.md"), encoding="utf-8") as fh:
            themap = fh.read()
    except Exception:
        themap = "(the map could not be read - use the folders directly)"

    cmd = build_command(PROMPT % {"question": question, "map": themap},
                        rec["model"], claude)
    # the prompt is tens of kilobytes of map; the record keeps its size, not
    # the thing itself
    pi = cmd.index("-p") + 1
    rec["command"] = cmd[:pi] + ["<prompt: %d chars>" % len(cmd[pi])] \
        + cmd[pi + 1:]
    note("archive", "Archive search started: %s" % question[:160])

    env = dict(os.environ)
    env["BRIDGE_NO_HOOKS"] = "1"          # not a member of the pair
    env.pop("BRIDGE_ROLE", None)
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"

    limit = float(timeout or DEFAULT_TIMEOUT)
    proc = None
    try:
        proc = subprocess.Popen(cmd, cwd=root, env=env,
                                stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE)
        out, err = proc.communicate(timeout=limit)
        code = proc.returncode
        answer = (out or b"").decode("utf-8", "replace").strip()
        why = (err or b"").decode("utf-8", "replace").strip()
    except subprocess.TimeoutExpired:
        _kill(proc)
        rec.update(state="failed", seconds=time.time() - rec["started"],
                   error="the search ran past its %d-second limit and was "
                         "stopped" % int(limit))
        note("archive", "Archive search timed out after %ds: %s"
             % (int(limit), question[:120]), "sound")
        return rec
    except Exception as exc:
        _kill(proc)
        rec.update(state="failed", seconds=time.time() - rec["started"],
                   error="could not run %s: %s"
                         % (" ".join(cmd[:cmd.index("-p")]), exc))
        note("archive", "Archive search could not start: %s" % rec["error"],
             "sound")
        return rec

    rec["seconds"] = time.time() - rec["started"]
    if code != 0 or not answer:
        # The reason is whatever the process said, not "it failed" - the
        # thing that broke names itself here or nowhere (§1.6.12).
        rec.update(state="failed",
                   error=(why or answer or
                          "it exited %s and said nothing" % code)[:1200])
        note("archive", "Archive search failed (exit %s): %s"
             % (code, rec["error"][:300]), "sound")
        return rec

    rec.update(state="done", answer=answer, cited=_cited(answer))
    rec["extract"] = write_extract(project_dir, rec) or ""
    note("archive", "Archive search answered in %ds from %d file%s: %s"
         % (int(rec["seconds"]), len(rec["cited"]),
            "" if len(rec["cited"]) == 1 else "s", question[:120]))
    return rec


def _kill(proc):
    if not proc or proc.poll() is not None:
        return
    try:
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"],
                           capture_output=True, timeout=15)
        else:
            proc.kill()
    except Exception:
        pass


def search_async(project_dir, question, parallel=None, **kw):
    """Start a search on a worker thread. One at a time per project.

    Returns (run_id, None) when it started, or (None, reason) when it did
    not - a request that is refused is refused with the id of the run
    holding the seat, never dropped in silence.

    Two limits, and they answer different questions. Within a project it is
    still one at a time: a second question about the same archive would be
    answered by the same files, and asking twice at once only doubles the
    cost. Across projects it is `parallel`, because the seat used to be one
    for the whole bridge - so with several pairs, one project's question
    locked every other project out of its own archive for as long as it
    ran. What the ceiling is really protecting is the machine: each of
    these is a headless claude process.
    """
    if not (question or "").strip():
        return None, "there was no question in the request"
    rid, run = active_run(project_dir)
    if rid:
        return None, ("a search is already running (%s: %s) for %s - one at "
                      "a time per project, so this one was not started"
                      % (rid, (run.get("question") or "")[:80],
                         _shortname(project_dir)))
    cap = int(parallel or DEFAULT_PARALLEL)
    busy = running_runs()
    if len(busy) >= cap:
        return None, ("%d searches are already running (%s) and at most %d "
                      "may run at once, so this one was not started - it is "
                      "the machine that is full, not this project's seat"
                      % (len(busy),
                         ", ".join("%s for %s" % (b_id,
                                                  _shortname(b.get("project")))
                                   for b_id, b in busy),
                         cap))
    run_id = new_run_id()
    _remember({"id": run_id, "question": question, "project": project_dir,
               "state": "running", "started": time.time(), "seconds": 0,
               "answer": "", "cited": [], "extract": "", "error": "",
               "model": kw.get("model") or DEFAULT_MODEL})

    def run_it():
        try:
            rec = search(project_dir, question, run_id=run_id, **kw)
        except Exception as exc:          # nothing may stay "running"
            rec = get_run(run_id) or {"id": run_id}
            rec.update(state="failed", error="the search thread died: %s" % exc)
        _remember(rec)

    threading.Thread(target=run_it, daemon=True).start()
    return run_id, None
